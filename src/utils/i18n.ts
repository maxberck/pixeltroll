export const getBrowserLang = (): BaseLang => {
  if (typeof window === 'undefined') return 'en'
  const lang = navigator.language || (navigator as any).userLanguage || 'en'
  return lang.toLowerCase().startsWith('fr') ? 'fr' : 'en'
}

